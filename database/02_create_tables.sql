CREATE TABLE APP_ROLES (
    ROLE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ROLE_NAME VARCHAR2(20) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(200)
);

CREATE TABLE APP_USERS (
    USER_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    FULL_NAME VARCHAR2(100) NOT NULL,

    EMAIL VARCHAR2(254) NOT NULL UNIQUE,

    PASSWORD_HASH VARCHAR2(255) NOT NULL,

    ROLE_ID NUMBER NOT NULL,

    ACCOUNT_STATUS VARCHAR2(20)
        DEFAULT 'PENDING' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    APPROVED_BY NUMBER,

    APPROVED_AT TIMESTAMP,

    CONSTRAINT FK_APP_USERS_ROLE
        FOREIGN KEY (ROLE_ID)
        REFERENCES APP_ROLES (ROLE_ID),

    CONSTRAINT FK_APP_USERS_APPROVER
        FOREIGN KEY (APPROVED_BY)
        REFERENCES APP_USERS (USER_ID),

    CONSTRAINT CK_APP_USERS_STATUS
        CHECK (
            ACCOUNT_STATUS IN ('PENDING', 'APPROVED', 'REJECTED')
        )
);

CREATE TABLE APPROVAL_HISTORY (
    HISTORY_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    USER_ID NUMBER NOT NULL,

    ACTION VARCHAR2(20) NOT NULL,

    ACTION_BY NUMBER NOT NULL,

    ACTION_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_APPROVAL_USER
        FOREIGN KEY (USER_ID)
        REFERENCES APP_USERS (USER_ID),

    CONSTRAINT FK_APPROVAL_ACTOR
        FOREIGN KEY (ACTION_BY)
        REFERENCES APP_USERS (USER_ID),

    CONSTRAINT CK_APPROVAL_ACTION
        CHECK (ACTION IN ('APPROVED', 'REJECTED'))
);